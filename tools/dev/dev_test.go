func TestCheckSource(t *testing.T) {
	const good = spdxHeader + "\npackage x\n"
	tests := []struct {
		name    string
		path    string
		content string
		want    []string // substrings, one per expected problem
	}{
		{"clean file", "internal/x/x.go", good, nil},
		{"missing header", "internal/x/x.go", "package x\n", []string{"missing the SPDX header"}},
		{"wrong copyright line", "internal/x/x.go", "// SPDX-FileCopyrightText: 2026 Somebody Else\n// SPDX-License-Identifier: AGPL-3.0-only\n\npackage x\n", []string{"missing the SPDX header"}},
		{"generated file needs no header", "internal/x/gen.go", "// Code generated by foo. DO NOT EDIT.\n\npackage x\n", nil},
		{"wildcard bind", "internal/x/x.go", good + "var a = \"0.0.0.0:8080\"\n", []string{"wildcard bind address"}},
		{"ipv6 wildcard bind", "internal/x/x.go", good + "var a = \"[::]:80\"\n", []string{"wildcard bind address"}},
		{"CIDR is not a bind address", "internal/x/x.go", good + "var a = \"0.0.0.0/8\"\n", nil},
		{"net.Listen outside the helper", "internal/viewer/s.go", good + "l, _ := net.Listen(\"tcp\", \"127.0.0.1:0\")\n", []string{"opens a listener"}},
		{"ListenConfig outside the helper", "internal/viewer/s.go", good + "l, _ := lc.Listen(ctx, \"tcp\", a)\n", []string{"opens a listener"}},
		{"ListenAndServe outside the helper", "internal/viewer/s.go", good + "_ = http.ListenAndServe(a, nil)\n", []string{"opens a listener"}},
		{"the helper may listen", "internal/platform/listen.go", good + "l, _ := net.Listen(\"tcp\", \"127.0.0.1:0\")\n", nil},
		{"comments are ignored", "internal/viewer/s.go", good + "// net.Listen(\"tcp\", \"0.0.0.0:1\")\n", nil},
		{"tests may listen", "internal/viewer/s_test.go", good + "l, _ := net.Listen(\"tcp\", \"127.0.0.1:0\")\n", nil},
		{"tools are exempt from listener rules", "tools/dev/x.go", good + "l, _ := net.Listen(\"tcp\", \":80\")\n", nil},
		{"tests still need the header", "internal/x/x_test.go", "package x\n", []string{"missing the SPDX header"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := checkSource(tt.path, []byte(tt.content))
			if len(got) != len(tt.want) {
				t.Fatalf("got %d problems %q, want %d %q", len(got), got, len(tt.want), tt.want)
			}
			for i, sub := range tt.want {
				if !strings.Contains(got[i], sub) {
					t.Errorf("problem %d = %q, want it to contain %q", i, got[i], sub)
				}
			}
		})
	}
}

func TestParseFuzzList(t *testing.T) {
	out := strings.Join([]string{
		"?   \tgithub.com/x/y/cmd\t[no test files]",
		"FuzzFrame",
		"FuzzBootstrap",
		"ok  \tgithub.com/x/y/internal/protocol\t0.012s",
		"ok  \tgithub.com/x/y/internal/other\t0.003s",
		"FuzzPolicy",
		"ok  \tgithub.com/x/y/internal/safety/policy\t0.5s",
	}, "\n")
	want := []fuzzTarget{
		{"github.com/x/y/internal/protocol", "FuzzFrame"},
		{"github.com/x/y/internal/protocol", "FuzzBootstrap"},
		{"github.com/x/y/internal/safety/policy", "FuzzPolicy"},
	}
	if got := parseFuzzList(out); !reflect.DeepEqual(got, want) {
		t.Fatalf("parseFuzzList = %v, want %v", got, want)
	}
	if got := parseFuzzList(""); len(got) != 0 {
		t.Fatalf("empty output produced targets: %v", got)
	}
}

func TestExeName(t *testing.T) {
	if got := exeName("controlsnack", target{"windows", "amd64"}); got != "controlsnack.exe" {
		t.Errorf("windows: %q", got)
	}
	if got := exeName("controlsnack", target{"linux", "arm64"}); got != "controlsnack" {
		t.Errorf("linux: %q", got)
	}
}

func TestTargetEnvIsPureGo(t *testing.T) {
	env := targetEnv(target{"darwin", "arm64"})
	want := []string{"CGO_ENABLED=0", "GOOS=darwin", "GOARCH=arm64"}
	if !reflect.DeepEqual(env, want) {
		t.Fatalf("targetEnv = %v, want %v (D-06: every build is CGO_ENABLED=0)", env, want)
	}
}

